/**
 * (0x0318) 同飞液冷机转发通信协议 V2.3 —— 能源数据解析
 *
 * 依据点表：.dumate/inbox/(0x0318)同飞液冷机转发通信协议-V2.3-25.6.23.xlsx
 * 关键点（与通用 16 位解析的差异，必须按字节地址解析）：
 *   - B0/B2/B4/B32/B34/B36 为 16 位寄存器，但 B38/B39/B40/B41 是 **单字节位信号**
 *     （通用解析会把 B38 读成 byte38<<8|byte39，导致电平位全错）
 *   - B86~B95 为故障字，每字节 8 个故障位
 *   - 温度/压力多为「实际值*10」，系数在展示层换算
 */
import { parseAddrFields, u8, u16, i16, bits, ADDR_TYPE_SIZE } from './addr-fields'

// ---- 能源数据（0x02）----
const energyFields = [
  // 设置类（16 位）
  u16(0, 'B0'),    // 启动模式
  u16(2, 'B2'),    // 工作模式
  u16(4, 'B4'),    // 供回水控制目标
  i16(6, 'B6'),    // 制冷预设温度
  i16(8, 'B8'),    // 制冷回差
  i16(10, 'B10'),  // 制热预设温度
  i16(12, 'B12'),  // 制热回差
  i16(14, 'B14'),  // 控温时泵转速
  i16(16, 'B16'),  // 自循环泵转速
  i16(18, 'B18'),  // 液温过高点
  i16(20, 'B20'),  // 液温过低点
  i16(22, 'B22'),  // 回水压力过低点（*10）
  i16(24, 'B24'),  // 供水压力过高点（*10）
  i16(26, 'B26'),  // 供水压力预警点（*10）
  i16(28, 'B28'),  // 供水压力预警回差（*10）
  u16(30, 'B30'),  // 预留
  u16(32, 'B32'),  // 485 通讯地址
  u16(34, 'B34'),  // 波特率
  u16(36, 'B36'),  // 机组运行状态（低字节状态 / 高字节模式）
  // 位信号（单字节）
  bits(38, 'B38'), u8(38, 'B38'),
  bits(39, 'B39'), u8(39, 'B39'),
  u8(40, 'B40'),   // 全预留
  bits(41, 'B41'), u8(41, 'B41'),
  // 温度 / 压力 / 转速
  i16(42, 'B42'),  // 供液温度（*10）
  i16(44, 'B44'),  // 回液温度（*10）
  i16(46, 'B46'),  // 系统蒸进（*10）
  i16(50, 'B50'),  // 蒸出温度（*10）
  i16(52, 'B52'),  // 环境温度（*10）
  i16(54, 'B54'),  // 系统冷凝（*10）
  u16(58, 'B58'),  // 节流电膨当前开度（步）
  u16(60, 'B60'),  // 水泵当前转速（%）
  u16(62, 'B62'),  // 压缩机当前转速（RPS）
  u16(64, 'B64'),  // 风机转速（RPS）
  i16(72, 'B72'),  // 供水压力（*10）
  i16(74, 'B74'),  // 回水压力（*10）
  i16(78, 'B78'),  // 排气压力（*10）
  // 故障字（B86~B95，每字节 8 位）
  bits(86, 'B86'), u8(86, 'B86'),
  bits(87, 'B87'), u8(87, 'B87'),
  bits(88, 'B88'), u8(88, 'B88'),
  bits(89, 'B89'), u8(89, 'B89'),
  bits(90, 'B90'), u8(90, 'B90'),
  bits(91, 'B91'), u8(91, 'B91'),
  bits(92, 'B92'), u8(92, 'B92'),
  bits(93, 'B93'), u8(93, 'B93'),
  bits(94, 'B94'), u8(94, 'B94'),
  bits(95, 'B95'), u8(95, 'B95'),
  // 故障码 / 运行统计
  u16(100, 'B100'),  // 变频器故障代码
  u16(104, 'B104'),  // 系统总故障等级
  u16(106, 'B106'),  // 系统总故障代码
  u16(112, 'B112'),  // 三相 PFC 故障号
  u16(114, 'B114'),  // 变频器输出功率（*10）
  u16(116, 'B116'), u16(118, 'B118'),  // 水泵累计运行 小时/天数
  u16(120, 'B120'), u16(122, 'B122'),  // 加热累计运行 小时/天数
  u16(124, 'B124'), u16(126, 'B126'),  // 压缩机累计运行 小时/天数
  u16(128, 'B128'), u16(130, 'B130'),  // 风机累计运行 小时/天数
]

export const protocol_0318_V2_3 = {
  deviceType: '0318',
  version: 'V2_3',
  structs: {
    energyData: { fields: energyFields, bytes: 130 + ADDR_TYPE_SIZE.u16 },
  },
  parseEnergyData(bytes) {
    return parseAddrFields(bytes, energyFields)
  },
}
