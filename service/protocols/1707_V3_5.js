export const protocol_1707_V3_5 = {
  deviceType: '1707',
  version: 'V3_5',
  structs: {
    energyData: { fields: energyFields, bytes: 192 + ADDR_TYPE_SIZE.u16 },
    specialData: { fields: stateFields, bytes: 88 + ADDR_TYPE_SIZE.u16 },
  },
  parseEnergyData(bytes) {
    return parseAddrFields(bytes, energyFields)
  },
  parseSpecialData(bytes) {
    return parseAddrFields(bytes, stateFields)
  },
  // 控制帧回包：按 16bit 逐寄存器解析（与下行 setDeviceType 一致）
  parseEnergyControlData(bytes) {
    return parseControlRaw(bytes)
  },
}
